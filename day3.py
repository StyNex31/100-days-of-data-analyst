# Так же elif и else не может существовать без if

# Разница между if else и if elif

age = 1

if age >= 18:
    print("Доступ разрешен")
else:
    print("Доступ запрещен") # Сработает для любого возраста меньше 18

# if вариант ответа один на один случай остальные(все кроме =18) работает else с ответом если больше 18 то разрешить, если меньше то запретить

